template<typename PixelType>
void ofColor_<PixelType>::getHsb(float& hue,
                                 float& saturation,
                                 float& brightness) const {
	float max = getBrightness();
	
	float min = static_cast<float>(r);
	if(g < min) {
		min = static_cast<float>(g);
	}
	if(b < min) {
		min = static_cast<float>(b);
	}
	
	if(max == min) { // grays
		hue = 0.f;
		saturation = 0.f;
		brightness = max;
		return;
	}
	
	float hueSixth;
	if(r == max) {
		hueSixth = static_cast<float>((g - b) / (max - min));
		if(hueSixth < 0.f)
			hueSixth += 6.f;
	} else if (g == max) {
		hueSixth = static_cast<float>(2.f + (b - r) / (max - min));
	} else {
		hueSixth = static_cast<float>(4.f + (r - g) / (max - min));
	}
	hue = limit() * hueSixth / 6.f;
	saturation = limit() * (max - min) / max;
	brightness = max;
}


